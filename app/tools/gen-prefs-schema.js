#!/usr/bin/env node
//
// Generates src/shim/prefs-schema.js from the original widget's .kon file.
//
// The .kon declares all 32 preferences with their types, defaults and popup
// options. Generating the schema rather than transcribing it keeps the port
// honest against the original and avoids a drifting hand-maintained copy.
//
// Usage: node tools/gen-prefs-schema.js

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const KON = path.join(__dirname, '..', '..', 'Contents', 'Time Vault.kon');
const OUT = path.join(__dirname, '..', 'src', 'shim', 'prefs-schema.js');

const src = fs.readFileSync(KON, 'utf8');

// Matches both self-closing declarations and ones wrapping <option> lists.
const PREF = /<preference\s+([^>]*?)(\/>|>([\s\S]*?)<\/preference>)/g;
const ATTR = /([A-Za-z]+)\s*=\s*"([^"]*)"/g;

function attrs(text) {
	const out = {};
	let m;
	ATTR.lastIndex = 0;
	while ((m = ATTR.exec(text)) !== null) out[m[1]] = m[2];
	return out;
}

function tags(body, name) {
	const re = new RegExp(`<${name}>([\\s\\S]*?)</${name}>`, 'g');
	const out = [];
	let m;
	while ((m = re.exec(body)) !== null) out.push(m[1].trim());
	return out;
}

const prefs = {};
let m;
while ((m = PREF.exec(src)) !== null) {
	const a = attrs(m[1]);
	if (!a.name) continue;

	const entry = {
		type: a.type || 'text',
		defaultValue: a.defaultValue !== undefined ? a.defaultValue : '',
	};

	if (a.hidden) entry.hidden = true;
	if (a.group) entry.group = a.group;

	const body = m[3] || '';
	if (body.includes('<option')) {
		entry.option = tags(body, 'option');
		entry.optionValue = tags(body, 'optionValue');
	}

	prefs[a.name] = entry;
}

// <preferenceGroup> elements: Main.js iterates these to title the tabs of the
// preferences dialog.
const groups = {};
const GROUP = /<preferenceGroup\s+([^>]*?)\/?>/g;
let g;
while ((g = GROUP.exec(src)) !== null) {
	const a = attrs(g[1]);
	if (a.name) groups[a.name] = { icon: a.icon || '' };
}

// Settings the port adds, which the 2008 .kon naturally doesn't declare.
// Kept here so the preferences window builds them like any other.
Object.assign(prefs, {
	joplinSyncEnabled: {
		type: 'checkbox', defaultValue: '0', group: 'joplin',
		title: 'Sync to Joplin',
		description: 'One-way: the Time Vault notebook is rewritten on each sync, '
			+ 'so any changes made in Joplin are lost. Joplin must be running with '
			+ 'the Web Clipper service enabled.',
	},
	joplinSyncOnStop: {
		type: 'checkbox', defaultValue: '0', group: 'joplin',
		title: 'Sync after each entry',
		description: 'Sync automatically whenever the timer is stopped.',
	},
	joplinSyncOnQuit: {
		type: 'checkbox', defaultValue: '0', group: 'joplin',
		title: 'Sync when quitting',
		description: 'Sync automatically when TimeVault closes.',
	},
});

groups.joplin = { icon: '', title: 'Joplin' };

const names = Object.keys(prefs);
const body = names
	.map((n) => `\t${JSON.stringify(n)}: ${JSON.stringify(prefs[n])},`)
	.join('\n');

fs.writeFileSync(OUT, `// Generated by tools/gen-prefs-schema.js from Contents/Time Vault.kon — do not edit.
//
// The original widget declared its preferences in the .kon manifest and
// Konfabulator exposed them as preferences.<name>.value. This is that
// declaration, extracted so the shim can reproduce the same defaults.

'use strict';

globalThis.KON_PREFS_SCHEMA = {
${body}
};

globalThis.KON_PREF_GROUPS = ${JSON.stringify(groups, null, '\t')};
`);

console.log(`wrote ${names.length} preferences and ${Object.keys(groups).length} groups to ${path.relative(process.cwd(), OUT)}`);
