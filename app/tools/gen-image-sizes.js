#!/usr/bin/env node
//
// Generates src/shim/image-sizes.js, a path -> [width, height] table for every
// PNG in app/assets.
//
// Konfabulator could report an image's dimensions the instant its src was set,
// because it loaded images synchronously from the widget bundle. The DOM
// can't: naturalWidth is 0 until the image decodes. The original layout code
// depends on the synchronous behaviour — ThreePiecesRectangle reads
// imageLeft.width inside its constructor to place the middle slice — so the
// shim answers from this table instead of waiting for a load event.
//
// Reads the PNG IHDR chunk directly rather than shelling out to sips, so this
// stays dependency-free.
//
// Usage: node tools/gen-image-sizes.js

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ASSETS = path.join(__dirname, '..', 'assets');
const OUT = path.join(__dirname, '..', 'src', 'shim', 'image-sizes.js');

// PNG: 8-byte signature, then the IHDR chunk whose data starts at byte 16
// with big-endian uint32 width and height.
function pngSize(file) {
	const buf = Buffer.alloc(24);
	const fd = fs.openSync(file, 'r');
	const read = fs.readSync(fd, buf, 0, 24, 0);
	fs.closeSync(fd);

	if (read < 24) return null;
	if (buf.toString('ascii', 1, 4) !== 'PNG') return null;
	if (buf.toString('ascii', 12, 16) !== 'IHDR') return null;

	return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
}

function walk(dir, found = []) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) walk(full, found);
		else if (entry.name.toLowerCase().endsWith('.png')) found.push(full);
	}
	return found;
}

const sizes = {};
let skipped = 0;

for (const file of walk(ASSETS)) {
	const size = pngSize(file);
	if (!size) { skipped++; continue; }
	// Key by asset-relative path, which is what resolveResource() produces.
	sizes[path.relative(ASSETS, file).split(path.sep).join('/')] = size;
}

const keys = Object.keys(sizes).sort();
const body = keys.map((k) => `\t${JSON.stringify(k)}: [${sizes[k][0]}, ${sizes[k][1]}],`).join('\n');

fs.writeFileSync(OUT, `// Generated by tools/gen-image-sizes.js — do not edit.
//
// Image dimensions, so the shim can answer Image.width/height synchronously
// the way Konfabulator did. Regenerate after changing anything in assets/.

'use strict';

globalThis.KON_IMAGE_SIZES = {
${body}
};
`);

console.log(`wrote ${keys.length} image sizes to ${path.relative(process.cwd(), OUT)}${skipped ? ` (${skipped} skipped)` : ''}`);
